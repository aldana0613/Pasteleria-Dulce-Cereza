-- =========================================================
-- PROYECTO: PASTELERÍA DULCE CEREZA
-- Motor: PostgreSQL
-- Contenido: tablas, relaciones, restricciones y catálogo
--
-- Ejecutar dentro de una base de datos vacía.
-- =========================================================

BEGIN;

-- =========================================================
-- 1. CATEGORÍAS
-- =========================================================

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT NOT NULL DEFAULT '',
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT categoria_nombre_valido
        CHECK (LENGTH(TRIM(nombre)) > 0)
);

-- =========================================================
-- 2. PRODUCTOS
-- Cada producto pertenece a una categoría.
-- =========================================================

CREATE TABLE producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    descripcion TEXT NOT NULL DEFAULT '',
    imagen VARCHAR(500),
    emoji VARCHAR(20),
    etiqueta VARCHAR(80),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT producto_categoria_fk
        FOREIGN KEY (categoria_id)
        REFERENCES categoria(id)
        ON DELETE RESTRICT,

    CONSTRAINT producto_nombre_valido
        CHECK (LENGTH(TRIM(nombre)) > 0)
);

-- =========================================================
-- 3. PRESENTACIONES
-- Un producto puede tener varios tamaños y precios.
-- =========================================================

CREATE TABLE presentacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    tamano VARCHAR(50) NOT NULL,
    porciones VARCHAR(60) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT presentacion_producto_fk
        FOREIGN KEY (producto_id)
        REFERENCES producto(id)
        ON DELETE RESTRICT,

    CONSTRAINT presentacion_producto_tamano_unico
        UNIQUE (producto_id, tamano),

    CONSTRAINT presentacion_precio_positivo
        CHECK (precio > 0),

    CONSTRAINT presentacion_tamano_valido
        CHECK (LENGTH(TRIM(tamano)) > 0),

    CONSTRAINT presentacion_porciones_validas
        CHECK (LENGTH(TRIM(porciones)) > 0)
);

-- =========================================================
-- 4. PEDIDOS
-- Guarda los datos del comprador sin exigir una cuenta.
-- El método de pago expresa una elección, no un pago realizado.
-- =========================================================

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente VARCHAR(150) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    modalidad_entrega VARCHAR(20) NOT NULL,
    direccion VARCHAR(250),
    fecha_entrega DATE NOT NULL,
    metodo_pago VARCHAR(20) NOT NULL,
    costo_delivery NUMERIC(10, 2) NOT NULL DEFAULT 0,
    notas TEXT NOT NULL DEFAULT '',
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pedido_nombre_valido
        CHECK (LENGTH(TRIM(nombre_cliente)) > 0),

    CONSTRAINT pedido_telefono_valido
        CHECK (LENGTH(TRIM(telefono)) > 0),

    CONSTRAINT pedido_modalidad_valida
        CHECK (modalidad_entrega IN ('recojo', 'delivery')),

    CONSTRAINT pedido_metodo_pago_valido
        CHECK (metodo_pago IN ('yape', 'plin', 'efectivo', 'tarjeta')),

    CONSTRAINT pedido_estado_valido
        CHECK (
            estado IN (
                'pendiente',
                'confirmado',
                'en_preparacion',
                'listo',
                'entregado',
                'cancelado'
            )
        ),

    CONSTRAINT pedido_delivery_no_negativo
        CHECK (costo_delivery >= 0),

    CONSTRAINT pedido_recojo_sin_costo
        CHECK (
            modalidad_entrega <> 'recojo'
            OR costo_delivery = 0
        ),

    CONSTRAINT pedido_direccion_delivery
        CHECK (
            modalidad_entrega <> 'delivery'
            OR (
                direccion IS NOT NULL
                AND LENGTH(TRIM(direccion)) > 0
            )
        )
);

-- =========================================================
-- 5. DETALLE DEL PEDIDO
-- Cada fila representa una presentación incluida en un pedido.
-- Guarda nombre, presentación y precio históricos para que
-- cambios futuros del catálogo no alteren una compra anterior.
-- =========================================================

CREATE TABLE detalle_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    presentacion_id BIGINT NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    descripcion_presentacion VARCHAR(150) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10, 2) NOT NULL,

    CONSTRAINT detalle_pedido_fk
        FOREIGN KEY (pedido_id)
        REFERENCES pedido(id)
        ON DELETE CASCADE,

    CONSTRAINT detalle_presentacion_fk
        FOREIGN KEY (presentacion_id)
        REFERENCES presentacion(id)
        ON DELETE RESTRICT,

    CONSTRAINT detalle_presentacion_unica
        UNIQUE (pedido_id, presentacion_id),

    CONSTRAINT detalle_cantidad_positiva
        CHECK (cantidad > 0),

    CONSTRAINT detalle_precio_positivo
        CHECK (precio_unitario > 0),

    CONSTRAINT detalle_nombre_valido
        CHECK (LENGTH(TRIM(nombre_producto)) > 0),

    CONSTRAINT detalle_descripcion_valida
        CHECK (LENGTH(TRIM(descripcion_presentacion)) > 0)
);

-- =========================================================
-- 6. SOLICITUDES DE TORTAS PERSONALIZADAS
-- Son solicitudes de cotización, no pedidos confirmados.
-- La foto guarda una ruta o URL, no el archivo de imagen.
-- =========================================================

CREATE TABLE solicitud_personalizada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente VARCHAR(150) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    ocasion VARCHAR(80) NOT NULL,
    fecha_evento DATE NOT NULL,
    tamano VARCHAR(80) NOT NULL,
    sabor VARCHAR(80) NOT NULL,
    mensaje_torta VARCHAR(200) NOT NULL DEFAULT '',
    descripcion TEXT NOT NULL,
    foto_referencia VARCHAR(500),
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT personalizada_nombre_valido
        CHECK (LENGTH(TRIM(nombre_cliente)) > 0),

    CONSTRAINT personalizada_telefono_valido
        CHECK (LENGTH(TRIM(telefono)) > 0),

    CONSTRAINT personalizada_ocasion_valida
        CHECK (LENGTH(TRIM(ocasion)) > 0),

    CONSTRAINT personalizada_tamano_valido
        CHECK (LENGTH(TRIM(tamano)) > 0),

    CONSTRAINT personalizada_sabor_valido
        CHECK (LENGTH(TRIM(sabor)) > 0),

    CONSTRAINT personalizada_descripcion_valida
        CHECK (LENGTH(TRIM(descripcion)) > 0),

    CONSTRAINT personalizada_estado_valido
        CHECK (
            estado IN (
                'pendiente',
                'en_revision',
                'cotizada',
                'aceptada',
                'rechazada',
                'cancelada'
            )
        )
);

-- =========================================================
-- 7. MENSAJES DE CONTACTO
-- =========================================================

CREATE TABLE mensaje_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    asunto VARCHAR(100) NOT NULL,
    mensaje TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT contacto_nombre_valido
        CHECK (LENGTH(TRIM(nombre)) > 0),

    CONSTRAINT contacto_correo_no_vacio
        CHECK (LENGTH(TRIM(correo)) > 0),

    CONSTRAINT contacto_asunto_valido
        CHECK (LENGTH(TRIM(asunto)) > 0),

    CONSTRAINT contacto_mensaje_valido
        CHECK (LENGTH(TRIM(mensaje)) > 0),

    CONSTRAINT contacto_estado_valido
        CHECK (estado IN ('pendiente', 'leido', 'respondido'))
);

-- =========================================================
-- ÍNDICES
-- Las claves primarias y restricciones UNIQUE ya generan
-- sus propios índices.
-- =========================================================

CREATE INDEX idx_producto_categoria
    ON producto(categoria_id);

CREATE INDEX idx_detalle_presentacion
    ON detalle_pedido(presentacion_id);

CREATE INDEX idx_pedido_fecha_entrega
    ON pedido(fecha_entrega);

CREATE INDEX idx_pedido_estado
    ON pedido(estado);

CREATE INDEX idx_personalizada_fecha_evento
    ON solicitud_personalizada(fecha_evento);

